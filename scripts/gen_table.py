"""Generate the class table module from a CSV with columns code, parent, title (why is ignored).

Usage (from the repository root), the tracked source being scripts/classes.csv:
    uv run python scripts/gen_table.py scripts/classes.csv src/refdef/tables/standard.py --version V
"""

import argparse
import csv
import hashlib
import json
import re
import sys
from pathlib import Path

HEADER = "# Generated by scripts/gen_table.py; do not edit."
MAIN = re.compile(r"[A-Z]")
PAIR = re.compile(r"[A-Z]{2}")
MAX_WORDS = 5
DEPTH = 2
OLD_VERSION = re.compile(r'^VERSION = "(.*)"$', re.MULTILINE)
OLD_HASH = re.compile(r'^ENTRIES_SHA256 = "([0-9a-f]*)"$', re.MULTILINE)


def read_rows(path: Path) -> list[dict[str, str]]:
    """The rows of the CSV, read by column name."""
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def row_problems(row: dict[str, str], mains: set[str]) -> list[str]:
    """What is wrong with one row: code shape, parent, title."""
    code, parent, title = (row.get(key) or "" for key in ("code", "parent", "title"))
    found = []
    if MAIN.fullmatch(code):
        if parent:
            found.append(f"{code}: a main letter has no parent")
    elif PAIR.fullmatch(code):
        if parent != code[:1] or parent not in mains:
            found.append(f"{code}: parent must be the listed main letter {code[:1]}")
    else:
        found.append(f"{code!r}: not a letter or two letters")
    if not 1 <= len(title.split()) <= MAX_WORDS:
        found.append(f"{code}: title must be 1-{MAX_WORDS} words")
    if any(ch.isdigit() for ch in title):
        found.append(f"{code}: title has a digit")
    return found


def validate(rows: list[dict[str, str]]) -> list[str]:
    """All problems of the table, duplicate codes included."""
    codes = [row.get("code") or "" for row in rows]
    mains = {code for code in codes if MAIN.fullmatch(code)}
    found = [f"{code}: duplicate code" for code in sorted(set(codes)) if codes.count(code) > 1]
    for row in rows:
        found += row_problems(row, mains)
    return found


def entries_hash(entries: list[tuple[str, str]]) -> str:
    """SHA-256 of the tab-and-newline form of the entries, as UTF-8."""
    text = "".join(f"{code}\t{title}\n" for code, title in entries)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def render(entries: list[tuple[str, str]], version: str) -> str:
    """The text of the generated module."""
    lines = [HEADER, '"""The generated class table."""', "", 'NAME = "standard"']
    lines.append(f"VERSION = {json.dumps(version)}")
    lines += [f"DEPTH = {DEPTH}", "ENTRIES: tuple[tuple[str, str], ...] = ("]
    lines += [f"    ({json.dumps(c)}, {json.dumps(t, ensure_ascii=False)})," for c, t in entries]
    lines += [")", f'ENTRIES_SHA256 = "{entries_hash(entries)}"']
    return "\n".join(lines) + "\n"


def refusal(output: Path, version: str, digest: str) -> str | None:
    """The reason to refuse: the output holds this version with another hash."""
    if not output.exists():
        return None
    old = output.read_text(encoding="utf-8")
    old_version, old_hash = OLD_VERSION.search(old), OLD_HASH.search(old)
    if old_version and old_hash and old_version.group(1) == version and old_hash.group(1) != digest:
        return f"version {version} already has a different hash; raise --version"
    return None


def main(argv: list[str] | None = None) -> int:
    """Run the generator; return the exit code."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--version", required=True)
    args = parser.parse_args(argv)
    rows = read_rows(args.input)
    problems = validate(rows)
    if problems:
        sys.stdout.write("gen_table: " + "\n".join(problems) + "\n")
        return 1
    entries = sorted((row["code"], row["title"]) for row in rows)
    message = refusal(args.output, args.version, entries_hash(entries))
    if message:
        sys.stdout.write(f"gen_table: {message}\n")
        return 1
    args.output.write_text(render(entries, args.version), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
