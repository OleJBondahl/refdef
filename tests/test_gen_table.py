"""R10 gate (generator half): `scripts/gen_table.py` is deterministic and version-safe."""

import ast
import hashlib
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import family
import pytest

SCRIPT = family.ROOT / "scripts" / "gen_table.py"
FIXTURE = Path(__file__).parent / "fixtures" / "tables" / "classes.csv"
BASE = FIXTURE.read_text(encoding="utf-8")


def _run(csv_path: Path, out: Path, version: str = "1") -> subprocess.CompletedProcess[str]:
    argv = [sys.executable, str(SCRIPT), str(csv_path), str(out), "--version", version]
    return subprocess.run(argv, capture_output=True, text=True, check=False)  # noqa: S603 - fixed argv


def _csv(tmp_path: Path, text: str) -> Path:
    path = tmp_path / "in.csv"
    path.write_text(text, encoding="utf-8")
    return path


def _constants(text: str) -> dict[str, Any]:
    """The module-level constants of a generated module, read as literals."""
    found = {}
    for node in ast.parse(text).body:
        if isinstance(node, ast.Assign):
            found[ast.unparse(node.targets[0])] = ast.literal_eval(node.value)
        elif isinstance(node, ast.AnnAssign) and node.value is not None:
            found[ast.unparse(node.target)] = ast.literal_eval(node.value)
    return found


def _swap(old: str, new: str) -> str:
    assert old in BASE
    return BASE.replace(old, new)


def test_output_is_byte_identical_and_shaped(tmp_path):
    """R10: the same input and version give the same bytes, sorted by code, header first."""
    first, second = tmp_path / "a.py", tmp_path / "b.py"
    assert _run(FIXTURE, first).returncode == 0
    assert _run(FIXTURE, second).returncode == 0
    text = first.read_text(encoding="utf-8")
    assert text == second.read_text(encoding="utf-8")
    assert text.startswith("# Generated by scripts/gen_table.py; do not edit.\n")
    assert 'NAME = "standard"\nVERSION = "1"\nDEPTH = 2\n' in text
    assert "import" not in text
    codes = re.findall(r'^    \("([A-Z]+)", ', text, re.MULTILINE)
    assert codes == ["B", "BA", "BB", "K", "KA", "KB"]


def test_hash_matches_the_m15_formula(tmp_path):
    """R10: ENTRIES_SHA256 is SHA-256 of `code TAB title NEWLINE` lines, UTF-8, sorted by code."""
    out = tmp_path / "out.py"
    assert _run(FIXTURE, out).returncode == 0
    values = _constants(out.read_text(encoding="utf-8"))
    entries = values["ENTRIES"]
    assert entries[0] == ("B", "Sensor")
    assert entries[3] == ("K", "Relay")
    joined = "".join(f"{c}\t{t}\n" for c, t in entries)
    assert values["ENTRIES_SHA256"] == hashlib.sha256(joined.encode("utf-8")).hexdigest()
    assert len(entries) == 6


def test_why_column_is_ignored(tmp_path):
    """R10: changing only `why` leaves the output unchanged."""
    first, second = tmp_path / "a.py", tmp_path / "b.py"
    _run(FIXTURE, first)
    assert _run(_csv(tmp_path, BASE.replace("because", "other reason")), second).returncode == 0
    assert first.read_bytes() == second.read_bytes()


BAD = {
    "duplicate code": _swap("KB,K,Time delay relay", "KA,K,Time delay relay"),
    "bad parent": _swap("KA,K,", "KA,B,"),
    "unlisted parent": _swap("KA,K,", "KA,Q,"),
    "main with parent": _swap("K,,Relay", "K,B,Relay"),
    "bad code shape": _swap("KA,K,", "k1,K,"),
    "empty title": _swap("Auxiliary relay", ""),
    "digit in title": _swap("Auxiliary relay", "Auxiliary relay 2"),
    "six-word title": _swap("Auxiliary relay", "One two three four five six"),
}


@pytest.mark.parametrize("case", sorted(BAD))
def test_validation_failure_exits_nonzero_and_writes_nothing(tmp_path, case):
    """R10: each validation failure exits non-zero, names the code and leaves no output file."""
    out = tmp_path / "out.py"
    result = _run(_csv(tmp_path, BAD[case]), out)
    assert result.returncode == 1, result.stdout
    assert not out.exists()
    assert result.stdout.startswith("gen_table: ")


@pytest.mark.parametrize("title", ["Auxiliary", "One two three four five"])
def test_title_of_one_and_five_words_is_accepted(tmp_path, title):
    """R10: M15 allows 1-5 words, so both ends of the range generate."""
    out = tmp_path / "out.py"
    assert _run(_csv(tmp_path, _swap("Auxiliary relay", title)), out).returncode == 0


def test_same_version_with_changed_entry_is_refused(tmp_path):
    """R10: an output holding version 1 with another hash is not overwritten; version 2 is."""
    out = tmp_path / "out.py"
    assert _run(FIXTURE, out).returncode == 0
    before = out.read_bytes()
    changed = _csv(tmp_path, _swap("Relay", "Contactor"))
    result = _run(changed, out)
    assert result.returncode == 1
    assert "raise --version" in result.stdout
    assert out.read_bytes() == before
    assert _run(FIXTURE, out).returncode == 0
    assert _run(changed, out, version="2").returncode == 0
    assert 'VERSION = "2"' in out.read_text(encoding="utf-8")
